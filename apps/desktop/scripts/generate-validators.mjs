import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

// Annotations do not affect validation. Keeping them outside executable code
// also prevents schema documentation from masquerading as fixture UI content.
function validationSchema(value) {
  if (!value || typeof value !== "object") return value;
  const dictionaries = ["properties", "patternProperties", "$defs", "definitions", "dependentSchemas"];
  const arrays = ["allOf", "anyOf", "oneOf", "prefixItems"];
  const single = ["items", "contains", "additionalProperties", "unevaluatedProperties",
    "unevaluatedItems", "propertyNames", "not", "if", "then", "else"];
  return Object.fromEntries(Object.entries(value)
    .filter(([key]) => !["description", "title", "$comment", "examples", "default"].includes(key))
    .map(([key, item]) => {
      if (dictionaries.includes(key)) return [key, Object.fromEntries(Object.entries(item)
        .map(([name, schema]) => [name, validationSchema(schema)]))];
      if (arrays.includes(key)) return [key, item.map(validationSchema)];
      if (single.includes(key)) return [key, validationSchema(item)];
      return [key, item];
    }));
}

const schemas = ["voice_profile", "card-viewport", "asset-object", "asset-catalog", "semantic-record", "semantic-cube"].map(name =>
  validationSchema(JSON.parse(readFileSync(new URL(`../../../schemas/${name}.schema.json`, import.meta.url), "utf8"))));
const ajv = new Ajv2020({ strict: false, strictNumbers: true, validateFormats: false, allErrors: true, inlineRefs: false,
  code: { source: true, esm: true } });
schemas.forEach(schema => ajv.addSchema(schema));
let code = standaloneCode(ajv, {
  profileValidator: schemas[0].$id, viewportValidator: schemas[1].$id, catalogValidator: schemas[3].$id,
  semanticCubeValidator: schemas[5].$id,
});
// Ajv emits CommonJS references for its small runtime helpers even in ESM
// mode. Convert those references to static imports for Node and Vite alike.
const imports = new Map();
code = code.replace(/require\("(ajv\/dist\/runtime\/(?:ucs2length|equal))"\)\.default/g, (_, module) => {
  if (!imports.has(module)) imports.set(module, `runtime${imports.size}`);
  const name = imports.get(module);
  return `(${name}.default || ${name})`;
});
if (/\brequire\s*\(|\bnew Function\s*\(|\beval\s*\(/.test(code)) throw new Error("Validator output requires unsupported dynamic code");
const output = new URL("../src/generated/contract-validators.js", import.meta.url);
mkdirSync(fileURLToPath(new URL(".", output)), { recursive: true });
const text = "// Generated by scripts/generate-validators.mjs from authoritative JSON schemas.\n"
  + [...imports].map(([module, name]) => `import ${name} from "${module}.js";`).join("\n") + "\n" + code + "\n";
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== text) throw new Error("Contract validators are stale; run npm run generate:validators");
} else {
  writeFileSync(output, text, "utf8");
}
